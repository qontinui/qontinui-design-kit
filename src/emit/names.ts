/**
 * The units a length takes in a media feature here: the guide's breakpoints
 * and the compiled `conditions.css` preludes read the same list. `%` is not
 * one (a media feature drops the whole query), and neither is a bare number.
 */
export const MEDIA_LENGTH_UNITS = ["px", "rem", "em"] as const;
/** `px, rem or em`, for a refusal that names the list. */
export const MEDIA_LENGTH_PHRASE = `${MEDIA_LENGTH_UNITS.slice(0, -1).join(", ")} or ${MEDIA_LENGTH_UNITS[MEDIA_LENGTH_UNITS.length - 1]}`;

/** A number and one of `MEDIA_LENGTH_UNITS`, nothing else: `48rem` matches, `48%` and `48foo` do not. */
export const MEDIA_LENGTH = new RegExp(`^(-?\\d*\\.?\\d+)(${MEDIA_LENGTH_UNITS.join("|")})$`);
