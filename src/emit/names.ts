/** `successMuted` -> `success-muted`; anything outside [a-z0-9-] becomes `-`. */
export function kebab(segment: string): string {
  return segment
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .toLowerCase()
    .replace(/[^a-z0-9-]/g, "-");
}

/** The `--dk-*` custom property for a leaf path. */
export function varName(path: string): string {
  return `--dk-${path.split(".").map(kebab).join("-")}`;
}

